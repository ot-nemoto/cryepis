WARP, FINE = 5, 2.5  # 海岸線の揺らぎ（大きなうねり・細かいぎざぎざ、px）
MARGIN = (50, 40)  # 地図の端からの余白（px）
K = math.cos(math.radians(37))  # 経度 1 度の長さ（緯度 1 度に対する割合。北緯 37 度あたり）
KM_PER_DEGREE = 111  # 緯度 1 度の長さ（km）


def _rotate(x, y, a):
  c, s = math.cos(a), math.sin(a)
  return x * c - y * s, x * s + y * c


def _fit(angle_deg):
  """傾きを angle_deg 度にして、陸を地図いっぱいに置く倍率と位置。"""
  a = math.radians(angle_deg)
  pts = [_rotate(lon * K, -lat, a) for poly in LAND for lon, lat in poly]
  x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts)
  y0, y1 = min(p[1] for p in pts), max(p[1] for p in pts)
  sc = min((W - 2 * MARGIN[0]) / (x1 - x0), (H - 2 * MARGIN[1]) / (y1 - y0))
  return a, sc, (W - (x1 - x0) * sc) / 2 - x0 * sc, (H - (y1 - y0) * sc) / 2 - y0 * sc


# 地図にいちばん大きく入る傾き（-60〜60 度、1 度きざみ）
ANGLE, SCALE, OX, OY = max((_fit(d) for d in range(-60, 61)), key=lambda f: f[1])
KM_PER_PX = KM_PER_DEGREE / SCALE  # 地図の 1px が何 km か


def to_map(lon, lat):
  x, y = _rotate(lon * K, -lat, ANGLE)
  return x * SCALE + OX, y * SCALE + OY


def from_map(x, y):
  u, v = _rotate((x - OX) / SCALE, (y - OY) / SCALE, -ANGLE)
  return u / K, -v


def raster(polys):
  """経度・緯度の多角形を、地図のマス目（STEP px）に塗る（[y][x] → 中か）。"""
  mask = [[False] * GW for _ in range(GH)]
  for poly in polys:
    p = [to_map(*q) for q in poly]
    for j in range(GH):
      y = j * STEP + 1
      xs = sorted(
        ax + (y - ay) * (bx - ax) / (by - ay)
        for (ax, ay), (bx, by) in zip(p, p[1:] + p[:1])
        if (ay <= y < by) or (by <= y < ay)
      )
      for a, b in zip(xs[::2], xs[1::2]):
        for i in range(max(0, int(a) // STEP), min(GW, int(b) // STEP + 1)):
          if a <= i * STEP + 1 <= b:
            mask[j][i] = True
  return mask


def _distance(grid, start):
  """start（真偽）のマスからの、上下左右の歩数。"""
  dist = [[None] * GW for _ in range(GH)]
  queue = deque()
  for j in range(GH):
    for i in range(GW):
      if grid[j][i] == start:
        dist[j][i] = 0
        queue.append((i, j))
  while queue:
    i, j = queue.popleft()
    for a, b in ((i + 1, j), (i - 1, j), (i, j + 1), (i, j - 1)):
      if 0 <= a < GW and 0 <= b < GH and dist[b][a] is None:
        dist[b][a] = dist[j][i] + 1
        queue.append((a, b))
  return dist


def generate(seed="japan"):
  """陸と海（land.generate の FLAT と同じ形）。陸は land / beach、海は浅い順に shallow / sea / deep / abyss。"""
  mask = raster(LAND)
  nx, ny, nf = base.Noise(f"{seed}-x"), base.Noise(f"{seed}-y"), base.Noise(f"{seed}-f")
  land = [[False] * GW for _ in range(GH)]
  for j in range(GH):
    y = j * STEP + 1
    for i in range(GW):
      x = i * STEP + 1
      wx = x + nx.fbm(x / 120, y / 120, 4) * WARP + nf.fbm(x / 18, y / 18, 2) * FINE
      wy = y + ny.fbm(x / 120, y / 120, 4) * WARP + nf.fbm(x / 18 + 7, y / 18, 2) * FINE
      ii, jj = int(wx) // STEP, int(wy) // STEP
      land[j][i] = 0 <= ii < GW and 0 <= jj < GH and mask[jj][ii]
  to_land, to_sea = _distance(land, True), _distance(land, False)
  elev = [[0.0] * GW for _ in range(GH)]
  kind = [[None] * GW for _ in range(GH)]
  for j in range(GH):
    y = j * STEP + 1
    for i in range(GW):
      x = i * STEP + 1
      if land[j][i]:
        d = to_sea[j][i]
        elev[j][i] = d * 0.01
        kind[j][i] = "beach" if d <= 1 else "land"
      else:
        d = to_land[j][i] * STEP + nx.fbm(x / 70, y / 70 + 20, 3) * 30
        kind[j][i] = "shallow" if d < 12 else "sea" if d < 60 else "deep" if d < 140 else "abyss"
        elev[j][i] = -d * 0.01
  return elev, kind
