def blob(cx, cy, rx, ry, n=10):
  """だ円の島・湖（経度, 緯度の点の並び）。"""
  return [(cx + rx * math.cos(2 * math.pi * t / n), cy + ry * math.sin(2 * math.pi * t / n)) for t in range(n)]


